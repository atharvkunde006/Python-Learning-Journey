#upper case method
a="ATharv"
print(a.upper())

#lower case method
a="ATHARV"
print(a.lower())

#strip method
a="silver spoon"
print(a.strip())

#rstrip method
a="Hello!!!"
print(a.rstrip("!"))

#replace method
a="silver spoon"
print(a.replace("sp","m"))

#split method
a="silver spoon"
print(a.split(" "))

#capitalize method
a="atharv"
print(a.capitalize())
b="hello world"
print(b.capitalize())

#center method
a="Welcome to the console!!!"
print(a.center(30))
b="Welcome to the console!!!"
print(b.center(50,"*"))

#count method
a="Abracadabra"
print(a.count("a"))

#endswith method
a="Welcome to the console!!!"
print(a.endswith("!!!"))

#find method
a="He's name is dan.He is an honest man"
print(a.find("is"))

